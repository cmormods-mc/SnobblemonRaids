require('./showdown/raid-patch');
const {BattleStream} = require('./showdown/sim/battle-stream');
const team = (name, species) => `${name}|${species}||100||0||static|tackle,growl,quickattack,tailwhip|35/35,40/40,30/30,15/15|hardy|0,0,0,0,0,0||31,31,31,31,31,31||50|255`;
const stream = new BattleStream({keepAlive:true});
stream._writeLines(`>start ${JSON.stringify({format:{name:'Raid Withdrawal Test',id:'raid-withdrawal-test',mod:'cobblemon',gameType:'raid',playerCount:4,ruleset:[]},formatid:'raid-withdrawal-test'})}`);
for (let i=1;i<=3;i++) stream._writeLines(`>player p${i} ${JSON.stringify({name:'Player '+i,team:team('Pikachu','Pikachu')})}`);
stream._writeLines(`>player p4 ${JSON.stringify({name:'Raid Boss',team:team('Charizard','Charizard')})}`);
const battle=stream.battle;
if (!battle || !battle.started) throw new Error('raid did not start');
const leaving=battle.sides[1];
const hpBefore=leaving.pokemon[0].hp;
stream._writeLines('>raidleave p2');
if (!leaving.raidWithdrawn) throw new Error('p2 not marked withdrawn');
if (leaving.pokemon[0].hp !== hpBefore || leaving.pokemon[0].fainted) throw new Error('withdrawal mutated legitimate Pokemon state');
if (leaving.requestState !== '') throw new Error('withdrawn side still has an actionable request');
if (battle.sides[3].foes(true).length !== 2) throw new Error('boss still targets withdrawn player');
if (battle.ended) throw new Error('one withdrawal ended the shared raid');
stream._writeLines('>p1 move tackle 1');
stream._writeLines('>p3 move tackle 1');
if (battle.ended) throw new Error('raid ended after remaining players completed a turn');
const raidDamage=battle.log.filter(x=>x.startsWith('|-raiddamage|p4'));
if (raidDamage.length !== 2) throw new Error(`expected 2 active-player raid damage events, got ${raidDamage.length}`);
if (raidDamage.some(x=>/\|p2[a-z]:/.test(x))) throw new Error('withdrawn player contributed damage after withdrawal');
console.log(JSON.stringify({passed:true,bossFoes:battle.sides[3].foes(true).length,withdrawnStatePreserved:true,raidDamage:raidDamage.length},null,2));
